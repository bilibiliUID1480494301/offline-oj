"""局域网测验模块。

分层：

* :mod:`crypto` —— ChaCha20-Poly1305（RFC 8439）与 scrypt 密钥派生，零依赖；
* :mod:`protocol` —— 加密帧编解码（长度前缀 + 方向位 + 单调序号，防重放与反射）；
* :mod:`session` —— 房间号、设备八位 ID、测验会话、提交与排名的数据模型；
* :mod:`server` —— 主机端：按房间号握手、下发题面、判题队列、放榜策略；
* :mod:`client` —— 客户端：连接、拉题面、提交、收结果。

这一层刻意不依赖 PySide6，可以在无界面环境下被完整测试与命令行驱动。

两种模式
--------
房间分**练习模式**与**考试模式**，两者唯一的差别是榜单什么时候公开：
练习模式实时更新，考试模式结束后统一放榜。其余（判题、积分、排名规则）
完全共用同一套代码 —— 不是两份实现，只有一个 ``leaderboard_visible()`` 分支。

身份
----
身份是**设备八位 ID**（客户端首次运行生成、存本机、跨场次不变），用户名只是标签、
允许重复。8 位字符取自排除 I/L/O/U 的 32 字符集，同一场里撞号可以忽略。

凭据
----
**房间号（6 位数字）即唯一凭据**，不需要逐人发牌。房间号本身绝不明文上线，
握手只发它的单向索引；但 6 位数字的搜索空间有限，要抗离线爆破请另设房间口令
（可选，默认留空）。边界详见 :mod:`offline_oj.net.crypto` 的模块说明。
"""
